function neighbors(id) {
	const i = nav.findIndex((n) => n.id === id);
	return {
		prev: i > 0 ? nav[i - 1] : void 0,
		next: i >= 0 && i < nav.length - 1 ? nav[i + 1] : void 0
	};
}
var useProgress = create()(persist((set, get) => ({
	read: [],
	markRead: (id) => {
		if (get().read.includes(id)) return;
		set({ read: [...get().read, id] });
	},
	quizBest: 0,
	setQuizBest: (n) => set({ quizBest: Math.max(get().quizBest, n) })
}), {
	name: "ems-manual-progress",
	storage: createJSONStorage(() => localStorage),
	skipHydration: true
}));
